#!/usr/bin/env python3
"""Bundle panel sources into the HTML supported by installed release updaters."""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
# Every file shares one script scope, so order matters: a file may use at top level only what came before it.
SCRIPTS = (
    "agents.js",
    "logic.js",
    "settings.js",
    "decks.js",
    "questions.js",
    "backups.js",
    "notifications.js",
    "images.js",
    "fleet.js",
    "leftovers.js",
    "inbox.js",
    "screen.js",
    "theme.js",
    "gestures.js",
    "files.js",
    "review.js",
    "refs.js",
    "suggest.js",
    "decisions.js",
    "spend.js",
    "git.js",
    "folders.js",
    "session-info.js",
    "quotas.js",
    "hotkeys.js",
    "schedule.js",
    "project.js",
    "resize.js",
    "markdown.js",
    "search.js",
    "board.js",
    "hub.js",
    "hub-cards.js",
    "hub-models.js",
    "containers.js",
    "windows.js",
    "lan.js",
    "drop.js",
    "providers.js",
    "here.js",
    "remember.js",
    "richpaste.js",
    "copytext.js",
    "voice-audio.js",
    "voice.js",
)
TOP_LEVEL = re.compile(r"^(?:async\s+)?(?:function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)", re.M)


def check_scripts(source):
    """A file missing from SCRIPTS would be dropped silently; a name declared twice would break the page."""
    files = {path.name for path in source.glob("*.js")} - {"app.js"}
    if files != set(SCRIPTS):
        raise SystemExit(f"frontend/*.js and SCRIPTS differ: {sorted(files ^ set(SCRIPTS))}")
    owners = {}
    for name in (*SCRIPTS, "app.js"):
        for declared in TOP_LEVEL.findall((source / name).read_text()):
            if declared in owners:
                raise SystemExit(f"{declared} is declared at top level in both {owners[declared]} and {name}")
            owners[declared] = name


def skill_bundle():
    """skills/ as one Python module: installed updaters accept only Python files under integrations/."""
    files = {str(path.relative_to(ROOT / "skills")): path.read_text()
             for path in sorted((ROOT / "skills").rglob("*")) if path.is_file() and "__pycache__" not in path.parts}
    version = hashlib.sha256(repr(sorted(files.items())).encode()).hexdigest()[:12]
    body = "".join(f"    {name!r}: {text!r},\n" for name, text in files.items())
    return ('"""Generated by scripts/build-panel.py from skills/ (integrations/skills.py installs them). Do not edit."""\n'
            f"VERSION = {version!r}\nFILES = {{\n{body}}}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when generated HTML is stale")
    args = parser.parse_args()
    source = ROOT / "frontend"
    check_scripts(source)
    page = (source / "index.html").read_text()
    for marker, name in (("__PANEL_STYLE__", "style.css"), ("__PANEL_SCRIPT__", "app.js")):
        if page.count(marker) != 1:
            raise SystemExit(f"Expected one {marker} in the panel template")
        content = (source / name).read_text()
        if name == "style.css":
            content += (source / "themes.css").read_text()
        if name == "app.js":
            content = "".join((source / part).read_text() for part in SCRIPTS) + content
        page = page.replace(marker, content)
    for target, content in ((ROOT / "panel/index.html", page), (ROOT / "integrations/skill_bundle.py", skill_bundle())):
        if not args.check:
            target.write_text(content)
        elif not target.is_file() or target.read_text() != content:
            raise SystemExit(f"{target.relative_to(ROOT)} is stale; run python3 scripts/build-panel.py")


if __name__ == "__main__":
    main()
